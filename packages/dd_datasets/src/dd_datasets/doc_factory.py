@curry
def rebase_document_location(document: Document, documents_dir: Path) -> Document:
    """
    Rewrite the location of a freshly loaded `Document` and of its pages into a local folder.

    A `Document` loaded with `Document.from_json` carries the `location` it had when it was saved, which is
    generally a stale path pointing to some other machine. Rebasing uses the stable `file_name` attributes to
    point the document, and for non PDF documents every page image, to `documents_dir` instead, so that
    loading pixels works once the dataset has been moved.

    Args:
        document: Document loaded from JSON.
        documents_dir: Local folder holding the original source files.

    Returns:
        The same document instance with all locations rewritten.
    """
    if document.file_name:
        document.location = documents_dir / document.file_name

    if document.file_type == DocumentFileLabel.PDF:
        for image in document._images.values():
            image.location = os.fspath(document.location)
        return document

    for image in document._images.values():
        if image.file_name:
            image.location = os.fspath(documents_dir / image.file_name)
    return document


class DocumentDatasetFactory:
    """
    Factory for building a `CustomDataset` from a folder of saved `doc.Document` JSON files.

    A dataset that has been generated by running a pipeline is not a folder of annotation files but a folder of
    saved `doc.Document`s. The dataflow of the returned dataset streams such a folder, provided it has the
    layout

    ```
    <location>/
    ├── <document_id_1>.json   # Document.save() output
    ├── <document_id_2>.json
    └── documents/             # one source file (.pdf or image) per document
    ```

    The base names of the source files in `documents/` must be unique and `documents/` must not contain any
    `.json` file, as all `.json` files below `location` are taken to be documents.

    `category_id`s serialized by a pipeline are often `DEFAULT_CATEGORY_ID`. As evaluation and training compare
    `category_id`s and not `category_name`s, the ids have to be derived from the `DatasetCategories` of the
    dataset. Which ids have to be assigned depends on the `dataset_type`, an attribute of the dataset and not of
    the dataflow builder, hence this factory.

    Example:
        ```python
        dataset = DocumentDatasetFactory.make(name="my_docs",
                                              location="my_docs",
                                              dataset_type=DatasetKind.OBJECT_DETECTION,
                                              init_categories=[LayoutLabel.TEXT, LayoutLabel.TABLE])
        df = dataset.dataflow.build(mode="image", load_image=True)
        ```
    """

    @staticmethod
    def make(
        name: Optional[str] = None,
        location: Optional[PathLikeOrStr] = None,
        dataset_type: Optional[TypeOrStr] = None,
        init_categories: Optional[Sequence[TypeOrStr]] = None,
        init_sub_categories: Optional[Mapping[TypeOrStr, Mapping[TypeOrStr, Sequence[TypeOrStr]]]] = None,
        file_path: Optional[PathLikeOrStr] = None,
        description: Optional[str] = None,
    ) -> CustomDataset:
        """
        Create a `CustomDataset` streaming saved `doc.Document`s.

        Either pass `file_path` to build the dataset from a dataset card, or `name`, `location` and
        `dataset_type` to build it from scratch.

        Args:
            name: Name of the dataset.
            location: Sub folder of the local dataset cache holding the dataset.
            dataset_type: One of the `DatasetKind` members, e.g. `DatasetKind.OBJECT_DETECTION`.
            init_categories: Base categories of the dataset. The order determines the `category_id`s.
            init_sub_categories: Sub categories of the dataset, e.g.
                                 `{LayoutLabel.WORD: {WordKey.TOKEN_CLASS: [TokenClassLabel.HEADER]}}`
            file_path: Path to a dataset card. Mutually exclusive with `name`/`location`/`dataset_type`.
            description: A description of the dataset.

        Returns:
            `CustomDataset`

        Raises:
            ValueError: If neither a dataset card nor `name`, `location` and `dataset_type` are given, or if
                        both are given.
            NotADirectoryError: If `location` does not exist in the local dataset cache.
        """

        class DocumentDataFlowBuilder(DataFlowBaseBuilder):
            """
            Dataflow builder streaming the saved `doc.Document`s of the dataset.

            `dataset_kind` is only available on the dataset and cannot be passed to the builder: `CustomDataset`
            requires the builder to have the signature `(self, location, annotation_files)`. The class therefore
            closes over the `dataset_kind` that `make` resolves below and does not define an `__init__` of its
            own.
            """

            def build(self, **kwargs: Union[str, int]) -> DataFlow:
                """
                Returns a dataflow from which you can stream either whole documents or their pages. All
                `category_id`s are re-assigned so that they align with the `DatasetCategories` of the dataset.
                The following arguments affect the returns of the dataflow:

                Args:
                    kwargs:
                        (mode) `doc` will yield `doc.Document` datapoints, `image` will yield `datapoint.Image`
                        datapoints in page order. Default: `image`
                        (load_image) Will load the image for each page. Only available for `mode="image"`.
                        Default: `False`
                        (max_datapoints) Will stop iterating after `max_datapoints` **documents**. For
                        `mode="image"` the number of yielded images is therefore the sum of the page numbers of
                        those documents and not `max_datapoints`. Default: `None`

                Returns:
                    Dataflow

                Raises:
                    ValueError: If `mode` is unknown or if `load_image` is set while `mode="doc"`.
                """

                mode = str(kwargs.get("mode", "image"))
                load_image = bool(kwargs.get("load_image", False))
                max_datapoints = kwargs.get("max_datapoints")

                if max_datapoints is not None:
                    max_datapoints = int(max_datapoints)

                if mode not in ("doc", "image"):
                    raise ValueError(f"mode must be either 'doc' or 'image', got {mode}")

                if mode == "doc" and load_image:
                    raise ValueError("load_image has no effect for mode='doc'. Leave it False")

                # Load
                workdir = self.get_workdir()
                df = SerializerFiles.load(workdir, file_type=".json", max_datapoints=max_datapoints, sort=True)
                df = MapData(df, Document.from_json)

                # Map
                df = MapData(df, rebase_document_location(documents_dir=workdir / "documents"))

                categories = self.categories
                filtered_names = categories.get_categories(as_dict=False, filtered=True)
                filtered_name_as_key = categories.get_categories(name_as_key=True, filtered=True)

                if mode == "doc":
                    if dataset_kind != DatasetKind.SEQUENCE_CLASSIFICATION:
                        log_once(
                            f"mode='doc' does not align category_ids for dataset kind {dataset_kind}. "
                            f"Use mode='image' instead.",
                            "warning",
                        )
                        return df
                    if categories.is_filtered():
                        df = MapData(df, filter_summary({DocumentKey.DOCUMENT_TYPE: filtered_names}))
                    return MapData(
                        df,
                        re_assign_document_summary_cat_ids(  # pylint: disable=E1120
                            {DocumentKey.DOCUMENT_TYPE: filtered_name_as_key}
                        ),
                    )

                df = FlattenDocumentImages(df, load_image=load_image)

                if dataset_kind == DatasetKind.SEQUENCE_CLASSIFICATION:
                    if categories.is_filtered():
                        df = MapData(df, filter_summary({DocumentKey.DOCUMENT_TYPE: filtered_names}))
                    return MapData(
                        df,
                        re_assign_cat_ids(  # pylint: disable=E1120
                            cat_to_sub_cat_mapping={
                                DefaultType.DEFAULT_TYPE: {DocumentKey.DOCUMENT_TYPE: filtered_name_as_key}
                            }
                        ),
                    )

                if dataset_kind == DatasetKind.OBJECT_DETECTION and not categories.is_filtered():
                    df = MapData(
                        df,
                        re_assign_cat_ids(categories_dict_name_as_key=filtered_name_as_key),
                    )

                if categories.is_cat_to_sub_cat():
                    df = MapData(
                        df,
                        cat_to_sub_cat(categories.get_categories(name_as_key=True), categories.cat_to_sub_cat),
                    )

                if categories.is_filtered():
                    df = MapData(
                        df,
                        filter_cat(  # pylint: disable=E1120
                            filtered_names, categories.get_categories(as_dict=False, filtered=False)
                        ),
                    )

                if dataset_kind == DatasetKind.TOKEN_CLASSIFICATION:
                    sub_category_keys = cast(
                        Mapping[TypeOrStr, Union[TypeOrStr, Sequence[TypeOrStr]]],
                        categories.get_sub_categories(filtered_names),
                    )
                    df = MapData(
                        df,
                        re_assign_cat_ids(  # pylint: disable=E1120
                            categories_dict_name_as_key=filtered_name_as_key,
                            cat_to_sub_cat_mapping=categories.get_sub_categories(
                                categories=filtered_names,
                                sub_categories=sub_category_keys,
                                keys=False,
                                values_as_dict=True,
                                name_as_key=True,
                            ),
                        ),
                    )

                return df

        if file_path is not None:
            if any(arg is not None for arg in (name, location, dataset_type)):
                raise ValueError("Pass either file_path or name, location and dataset_type, but not both")
            dataset_kind = get_type(DatasetCard.load_dataset_card(file_path).dataset_type)
            return CustomDataset.from_dataset_card(file_path, DocumentDataFlowBuilder)

        if name is None or location is None or dataset_type is None:
            raise ValueError("name, location and dataset_type must be provided, if no file_path is given")
        dataset_kind = get_type(dataset_type)

        workdir = SETTINGS.DATASET_DIR / location
        if not workdir.is_dir():
            raise NotADirectoryError(f"dir must exist: {workdir}")
        if not (workdir / "documents").is_dir():
            log_once(
                f"{workdir} has no 'documents' sub folder. Loading pixels of the pages will not be possible.",
                "warning",
            )

        return CustomDataset(
            name=name,
            dataset_type=dataset_type,
            location=location,
            init_categories=[get_type(category) for category in init_categories] if init_categories else [],
            init_sub_categories=(
                {
                    get_type(category): {
                        get_type(sub_cat_key): [get_type(sub_cat_value) for sub_cat_value in sub_cat_values]
                        for sub_cat_key, sub_cat_values in sub_cats.items()
                    }
                    for category, sub_cats in init_sub_categories.items()
                }
                if init_sub_categories
                else None
            ),
            description=description,
            dataflow_builder=DocumentDataFlowBuilder,
        )
